"""MEDULLA-DECISION-ENGINE-R176.6: the job load set over the wire.

Three connector packs of 300 tools each are generated by
``fixtures/pack_generator.py::make_packs(count=3, tools=300)`` and imported
through ``ConnectorPack.Import``. Once the capability feed has indexed them, the
served ``Decide`` ``load_set`` question for one job returns a bounded set: at
most 32 tools, the skills those tools carry, at most 4 agent starts, and one
premise per chosen tool. ``Decide`` adds no method and writes nothing.
"""

from __future__ import annotations

import asyncio
import sys
import time
import uuid
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "typed_packs"))
sys.path.insert(0, str(Path(__file__).resolve().parent / "fixtures"))

import pytest
from _commons_generation import (
    DIM,
    connect,
    establish_commons_generation,
    publish_schema,
)
from conftest import TEST_TENANT
from ontology_pack_support import attach_pack, import_entries
from pack_generator import make_packs

from medulla import decision_client as dc

MAX_TOOLS = 32
MAX_AGENTS = 4


def _question(space: dict[str, Any], graph: str) -> dict[str, Any]:
    return {
        "job_text": "look up an order and close the ticket",
        "job_embedding": [1.0] + [0.0] * (DIM - 1),
        "required_capabilities": [],
        "max_tools": MAX_TOOLS,
        "max_agents": MAX_AGENTS,
        "graph": graph,
        "embedding_version": space["space_digest"],
    }


async def _ask(
    decision: dc.DecisionClient,
    schema: dict[str, Any],
    graph: str,
    space: dict[str, Any],
) -> dict[str, Any]:
    request = dc.load_set_request(
        TEST_TENANT,
        f"load-set-{uuid.uuid4().hex[:8]}",
        _question(space, graph),
        schema,
    )
    return (await decision.decide(request))["records"][0]


# spec: MEDULLA-DECISION-ENGINE-R176.6
@pytest.mark.spec("MEDULLA-DECISION-ENGINE-R176.6")
def test_job_returns_bounded_tool_skill_agent_set() -> None:
    async def exercise() -> None:
        client = await connect()
        try:
            space = await establish_commons_generation(client)
            schema = await publish_schema(client)
        finally:
            await client.close()
        graph = f"load-set-{uuid.uuid4().hex[:8]}"
        admin = await connect()
        try:
            await admin.tenants.create(graph)
        finally:
            await admin.close()
        client = await connect(graph)
        decision = dc.DecisionClient(client=client)
        try:
            packs = make_packs(count=3, tools=300)
            assert sum(len(entries) for _, entries in packs) == 900
            for connector, entries in packs:
                imported = await import_entries(client, connector, entries)
                assert imported["result"] == "imported", imported
                await attach_pack(client, connector)
            connectors = {connector for connector, _ in packs}

            deadline = time.monotonic() + 240
            while True:
                try:
                    record = await _ask(decision, schema, graph, space)
                except Exception as error:  # the feed has not indexed the packs yet
                    assert time.monotonic() < deadline, error
                else:
                    answer = (record.get("answer") or {}).get("value") or {}
                    if answer.get("tools"):
                        break
                    assert time.monotonic() < deadline, record
                await asyncio.sleep(0.5)

            tools = answer["tools"]
            assert 0 < len(tools) <= MAX_TOOLS, tools
            assert len(set(tools)) == len(tools), tools
            for tool in tools:
                assert tool.startswith("mcp:"), tool
                assert tool.split("/")[0].removeprefix("mcp:") in connectors, tool
            assert isinstance(answer["skills"], list), answer
            assert len(answer["agents"]) <= MAX_AGENTS, answer["agents"]
            facts = [premise["fact"] for premise in record["premises"]]
            for tool in tools:
                assert any(
                    fact.startswith(f"load_set:component={tool}/") for fact in facts
                ), (tool, facts)
        finally:
            await client.close()

    asyncio.run(exercise())
